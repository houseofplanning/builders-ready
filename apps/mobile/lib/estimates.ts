/** Duplicate a quote into a fresh draft. Returns the new estimate id. */
export async function duplicateEstimate(
  id: UUID,
  tenantId: UUID,
  createdBy: UUID,
): Promise<UUID> {
  const src = await getEstimate(id);
  if (!src) throw new Error('Quote not found.');
  return createEstimate({
    tenant_id: tenantId,
    created_by: createdBy,
    title: `${src.title} (copy)`,
    project_type: src.project_type,
    client_name: src.client_name,
    client_email: src.client_email,
    client_phone: src.client_phone,
    site_address_line1: src.site_address_line1,
    site_address_line2: src.site_address_line2,
    city: src.city,
    postcode: src.postcode,
    vat_mode: src.vat_mode,
    vat_rate_bp: src.vat_rate_bp,
    valid_until: src.valid_until,
    notes: src.notes,
    terms: src.terms,
    lines: src.lines.map((l) => ({
      kind: l.kind,
      saved_rate_id: l.saved_rate_id,
      description: l.description,
      quantity: l.quantity,
      unit: l.unit,
      unit_cost_pence: l.unit_cost_pence,
      markup_percent: l.markup_percent,
    })),
  });
}
